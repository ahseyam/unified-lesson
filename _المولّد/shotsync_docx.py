"""⛔ النصفُ السريعُ من `shotsync`: الصورةُ المضمَّنةُ في كل نشرةٍ هي اللقطةُ
   التي على القرص — ولا تُحتمل واحدةٌ متخلِّفة.

وتصويرُ التسعِ والتسعين ومقارنتُها بالبكسل بطيءٌ (نصفُ ساعة)، فيُطلب بيدٍ
عند تغيير المنصة: `python3 shotsync.py`. وأمّا هذا فيجري مع كلِّ جولة.
"""
import sys

import shotsync

if __name__ == "__main__":
    ok, _ = shotsync.embedded()
    print("  %s" % ("✓ المضمَّنُ في المستندات هو اللقطاتُ على القرص"
                    if ok else "⛔ مستندٌ يحمل لقطةً ليست على القرص"))
    sys.exit(0 if ok else 1)
