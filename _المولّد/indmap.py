CARD = "1_2"      # م٢·٣ — تطبيقُ إستراتيجيات تدريس متنوعة


def guard(domains):
    """⛔ يفشل البناءُ إن بقي مؤشرٌ بلا موضعٍ في الجدول، أو خانةٌ لا وجودَ لها."""
    import prepdef as PD
    keys = {r["k"] for sec in PD.SECTIONS for r in sec["rows"]}
    want = {"%d_%d" % (di, ii)
            for di, dm in enumerate(domains) for ii in range(len(dm["inds"]))}
    have = set(MAP)
    miss, extra = sorted(want - have), sorted(have - want)
    bad = sorted({k for v in MAP.values() if isinstance(v, list) for k in v} - keys)
    if miss or extra or bad:
        raise SystemExit(
            "⛔ جدولُ التوأمة غيرُ مطابقٍ للاستمارة.\n"
            + ("  مؤشراتٌ بلا مدخل: " + " · ".join(miss) + "\n" if miss else "")
            + ("  مداخلُ لا مؤشرَ لها: " + " · ".join(extra) + "\n" if extra else "")
            + ("  خاناتٌ لا وجودَ لها في التحضير: " + " · ".join(bad) + "\n" if bad else "")
            + "  وهو جدولٌ تربويٌّ — يُراجع ولا يُخمَّن.")
    assert CARD in MAP, "⛔ مؤشرُ البطاقة ليس في الجدول"
    nob = sum(1 for v in MAP.values() if v is OBS)
    nrec = sum(1 for v in MAP.values() if v is REC)
    return len(want) - nob - nrec, nob, nrec
