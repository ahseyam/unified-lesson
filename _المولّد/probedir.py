"""⛔ **نسخُ الفحص لا تسكن في شجرة التسليم.**

كان كلُّ حارسٍ يكتب نسختَه من المنصة بجوار المولّد: سبعةُ ملفاتٍ، كلُّ واحدٍ
نسخةٌ كاملةٌ من الصفحة (١٫٣ م.ب) — تسعةُ ميغابايتَ في مجلّدٍ يُسلَّم، لا
يحميها إلا أسطرٌ في `.gitignore` مكتوبةٌ باليد بالبادئة. فمن أضاف حارساً
باسمٍ لا يوافق البادئةَ رفع نسخةً كاملةً من المنصة إلى المستودع العامّ —
وقد وقع مثلُه في الصور. (أمسكه وكيلُ مراجعة الحرّاس ١ أكتوبر ٢٠٢٦)

فصارت كلُّها في مجلّدٍ مؤقّتٍ **خارج الشجرة**: لا يُسلَّم ولا يُرفع ولا
يحتاج حارساً في `.gitignore`.
"""
import os
import tempfile

# ⛔ **ولكلِّ تشغيلٍ مجلّدُه**: شغّلتُ `checkall` و`fitcheck` معاً فكتبا في
#    الأسماء نفسِها فأفسد كلٌّ نسخةَ الآخر — فحصان متوازيان يتصادمان صامتين.
#    ومعرّفُ العملية يفصلهما. (١ أكتوبر ٢٠٢٦)
DIR = os.path.join(tempfile.gettempdir(), "clsguard", str(os.getpid()))
os.makedirs(DIR, exist_ok=True)


def probe(name):
    """مسارُ نسخةِ فحصٍ خارج شجرة المشروع."""
    return os.path.join(DIR, name)
