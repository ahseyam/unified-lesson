# -*- coding: utf-8 -*-
"""⛔ **المطبوعُ يُبنى من مصدر المنصة لا من نسخةٍ بيد.**

كان `pbuild2.py` يكتب قوائمَ خياراتِ النموذج الورقيِّ بيده — اثنتَي عشرةَ
قائمةً منسوخة — بينما المنصةُ تقرأ `prepdef.TICKS`. وانحرف فعلاً في **أخطر
خانة**: «الإستراتيجية» ستٌّ في الورق («تعلم تعاوني · استقصاء · مشروعات · حل
مشكلات · لعب أدوار · أخرى») والمنصةُ تعرض بنكَ **التسعَ عشرةَ** مقيَّداً
بالاتجاه. و«استقصاء» و«مشروعات» **لا بطاقةَ لهما في البنك**، و«تعلم تعاوني»
تختلف رسماً عن «التعلم التعاوني» فلا تُطابَق آلياً — فتنقطع سلسلةُ النظام
على الورق: الإستراتيجيةُ المعلنةُ ← بطاقةُ تشخيصها ← درجةُ م٢·٣.
(أمسكه وكيلُ الإشراف التربوي؛ وعُولج ١ أكتوبر ٢٠٢٦)

وهذا حارسُه: يفشل البناءُ إن عاد نداءُ `ticks("…")` بنصٍّ مكتوبٍ في المطبوع
بدل `_tk("مفتاح")` من المصدر — فلا تعود القائمتان تفترقان.

⚠️ ويُستثنى ما لا نظيرَ له في المنصة بطبعه (أمثلةٌ توضيحيةٌ داخل خانةٍ حرة)،
   ويُكتب استثناؤه هنا بالاسم لا بالصمت.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# قوائمُ أمثلةٍ داخل خاناتٍ حرّة — لا تقابلها قائمةٌ في المنصة
ALLOW = {"نص يقرؤه الطلاب", "حساب ينفّذه الطلاب"}


def main():
    src = open(os.path.join(HERE, "pbuild2.py"), encoding="utf-8").read()
    bad = []
    for m in re.finditer(r'ticks\(\s*("(?:[^"\\]|\\.)*"(?:\s*,\s*"(?:[^"\\]|\\.)*")*)\s*\)', src):
        items = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
        if items and items[0] in ALLOW:
            continue
        ln = src[:m.start()].count("\n") + 1
        bad.append((ln, " · ".join(items[:4])))
    if bad:
        print("⛔ قوائمُ خياراتٍ مكتوبةٌ بيدها في المطبوع — تُقرأ من prepdef.TICKS:")
        for ln, it in bad:
            print("      pbuild2.py:%d  «%s …»" % (ln, it))
        print("\n  استبدلها بـ`_tk(\"المفتاح\")`، أو أضف أولَ عنصرٍ إلى ALLOW")
        print("  إن كانت أمثلةً داخل خانةٍ حرّةٍ لا نظيرَ لها في المنصة.")
        return 1
    # ⛔ **وعناوينُ المجالات كذلك تُقرأ من المصدر**: كان المطبوعُ يكتب
    #    «المجالان ٢ و٣ · … · مشاركة المتعلمين واندماجهم» بينما `prepdef`
    #    يقول «المجال ٢ · العرض وإدارة الحصة» — فالورقُ يَعِد بتغطية المجال
    #    الثالث وله قسمٌ مستقلٌّ تحته. وهذا الحارسُ كان يرى القوائمَ ولا يرى
    #    العناوين. (قِيس ٢ أكتوبر ٢٠٢٦)
    heads = []
    for m in re.finditer(r'domain_(?:row|table)\(([^\n]*)', src):
        arg = m.group(1)
        if "_sec(" in arg:
            continue
        lit = re.findall(r'"((?:[^"\\]|\\.)*)"', arg)
        if any(x.startswith("المجال") for x in lit):
            heads.append((src[:m.start()].count("\n") + 1, " · ".join(lit[:2])))
    if heads:
        print("⛔ عناوينُ مجالاتٍ مكتوبةٌ بيدها في المطبوع — تُقرأ من prepdef:")
        for ln, it in heads:
            print("      pbuild2.py:%d  «%s»" % (ln, it))
        print("\n  استبدلها بـ`_sec(\"وصفُ القسم\")` فتتبع المصدرَ ولا تفترق.")
        return 1
    ns = len(re.findall(r'_sec\("', src))
    FLOOR_S = 2
    if ns < FLOOR_S:
        print("⛔ %d عنواناً مربوطاً بالمصدر فقط — والأرضيّةُ %d" % (ns, FLOOR_S))
        return 1

    # ⚠️ ولا يُحكَم بالنجاح إن لم يُقَس شيء
    n = len(re.findall(r'_tk\("', src))
    FLOOR = 10
    if n < FLOOR:
        print("⛔ %d قائمةً مربوطةً بالمصدر فقط — والأرضيّةُ %d. "
              "أعِيدت النسخةُ اليدويةُ؟" % (n, FLOOR))
        return 1
    print("  ✓ %d قائمةً و%d عنواناً في المطبوع تُقرأ من مصدر المنصة "
          "· ولا نسخةَ يدوية" % (n, ns))
    return 0


if __name__ == "__main__":
    sys.exit(main())
