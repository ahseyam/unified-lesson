def png(size=180):
    """تُرسَم من الـSVG نفسِه — فلا تتخلَّف إحداهما عن الأخرى."""
    import cairosvg
    return cairosvg.svg2png(bytestring=SVG.encode("utf-8"),
                            output_width=size, output_height=size)


def _b64(b):
    return base64.b64encode(b).decode("ascii")


def head(rel=""):
    """وسومُ الرأس. `rel` بادئةُ المسار إلى جذر التسليم (مثل `../`)."""
